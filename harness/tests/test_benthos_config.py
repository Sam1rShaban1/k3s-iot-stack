"""The Benthos config must reach the pods when it changes.

The ConfigMap used to be an inline document in deployment.yaml, mounted with
`subPath`. Two separate reasons an edit could fail to take effect:

  * `subPath` mounts are not updated in place by the kubelet;
  * the pod template carried no content hash, so nothing triggered a rollout.

On 2026-10-19 this produced a mixed rollout: four replicas restarted for
unrelated reasons and picked up the stage-instrumentation processor, while the
fifth kept running the old config. Some messages would have carried
`benthos_entry_ts` and some not, which would have looked like pipeline loss.

The config now lives in benthos.yaml and is generated by kustomize, whose hash
suffix rewrites the Deployment's volume reference. These tests pin that link,
plus the output address: a hardcoded ClusterIP is reassigned when the Service
is recreated, and Benthos then cannot publish at all.
"""

from __future__ import annotations

import shutil
import subprocess
import unittest
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
MANIFESTS = REPO / "manifests" / "benthos"
KUSTOMIZATION = MANIFESTS / "kustomization.yaml"
CONFIG = MANIFESTS / "benthos.yaml"
DEPLOYMENT = MANIFESTS / "deployment.yaml"


def render() -> str:
    exe = shutil.which("kustomize")
    cmd = [exe, "build", str(MANIFESTS)] if exe else [
        "kubectl", "kustomize", str(MANIFESTS)
    ]
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
    if res.returncode != 0:
        raise AssertionError(res.stderr)
    return res.stdout


class TestBenthosConfigWiring(unittest.TestCase):
    def test_config_is_a_real_file(self):
        self.assertTrue(CONFIG.is_file())
        yaml.safe_load(CONFIG.read_text())

    def test_configmap_is_generated_not_inline(self):
        k = yaml.safe_load(KUSTOMIZATION.read_text())
        names = [g["name"] for g in k.get("configMapGenerator", [])]
        self.assertIn("benthos-config", names)
        docs = [d for d in yaml.safe_load_all(DEPLOYMENT.read_text()) if d]
        self.assertNotIn("ConfigMap", [d["kind"] for d in docs])

    def test_generated_name_is_rewritten_into_the_volume(self):
        """The hash suffix is the only thing that forces a rollout."""
        docs = [d for d in yaml.safe_load_all(render()) if d]
        cm = next(d for d in docs if d["kind"] == "ConfigMap")
        dep = next(d for d in docs if d["kind"] == "Deployment")
        vol = dep["spec"]["template"]["spec"]["volumes"][0]["configMap"]["name"]
        self.assertEqual(vol, cm["metadata"]["name"])
        self.assertNotEqual(vol, "benthos-config")

    def test_the_payload_is_never_rewritten(self):
        """The stamp travels as a NATS header, not as a payload field.

        A Bloblang processor that adds a field to the payload re-serialises
        every message's JSON. Measured at 8000 msg/s: Benthos went from
        1868m to 2740m CPU and the run from 86.4% delivery to 39.1%. The
        instrumentation was costing more than half the pipeline it measured.
        """
        docs = [d for d in yaml.safe_load_all(render()) if d]
        cm = next(d for d in docs if d["kind"] == "ConfigMap")
        cfg = yaml.safe_load(cm["data"]["benthos.yaml"])
        self.assertEqual(cfg["pipeline"]["processors"], [])

    def test_the_stage_stamp_is_a_header(self):
        cfg = yaml.safe_load(CONFIG.read_text())
        headers = cfg["output"]["nats"]["headers"]
        self.assertIn("benthos_entry_ts", headers)
        self.assertIn("timestamp_unix_nano", headers["benthos_entry_ts"])

    def test_output_uses_dns_not_a_cluster_ip(self):
        cfg = yaml.safe_load(CONFIG.read_text())
        urls = cfg["output"]["nats"]["urls"]
        self.assertEqual(urls, ["nats://nats.nats.svc.cluster.local:4222"])


if __name__ == "__main__":
    unittest.main()
